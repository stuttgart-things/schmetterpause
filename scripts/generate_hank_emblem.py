#!/usr/bin/env python3
"""Bake Hank's shield and OFL glyph paths. No runtime font, text or transform."""

import json
from pathlib import Path
import pathops
from fontTools.misc.transform import Transform
from fontTools.pens.transformPen import TransformPen
from import_creator_avatars import shape, ellipse, op, svgpath, INK

ROOT = Path(__file__).resolve().parents[1]
# Diameter is conservatively rounded down from the 57.17-unit curve-space optimum.
BELLY_EMBLEM_BOX = (181.3, 337.6, 238.3, 394.6)
CX, CY, R = 209.8, 366.1, 28.5


def transformed(p, t):
    out = pathops.Path()
    p.draw(TransformPen(out.getPen(), t))
    return out


def outlined(p, w=5.5):
    border = pathops.Path(p)
    border.stroke(w, pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4)
    border.convertConicsToQuads(0.001)
    return op(p, border, pathops.PathOp.UNION)


def glyph_svg(p):
    x1, y1, x2, y2 = p.bounds
    scale = min((R * 2 * 0.56) / (y2 - y1), (R * 2 * 0.7) / (x2 - x1))

    def positioned(scale):
        return transformed(
            p,
            Transform(
                scale,
                0,
                0,
                -scale,
                CX - scale * (x1 + x2) / 2,
                CY + scale * (y1 + y2) / 2,
            ),
        )

    # Wide M/W and umlaut extents must also fit the round coloured interior.
    interior = ellipse(CX, CY, R - 6.5, R - 6.5)
    while (
        op(outlined(positioned(scale)), interior, pathops.PathOp.DIFFERENCE).area
        > 0.001
    ):
        scale *= 0.995
    letter = positioned(scale)
    return svgpath(outlined(letter), INK) + svgpath(letter, "#fff6f3")


source = json.loads((ROOT / "scripts/hank_glyphs.json").read_text())
entries = []
for letter, d in source["glyphs"].items():
    entries.append(
        json.dumps(letter, ensure_ascii=False)
        + ":"
        + json.dumps(glyph_svg(shape(d)))
        + ","
    )
(ROOT / "internal/avatar/hank_glyphs.go").write_text(
    "// Code generated by scripts/generate_hank_emblem.py; DO NOT EDIT.\n// Glyph source: Barlow Bold, SIL OFL 1.1; docs/licenses/Barlow-OFL.txt.\npackage avatar\n\nvar hankInitialGlyphs=map[string]string{\n"
    + "\n".join(entries)
    + "\n}\n"
)
# Table-tennis silhouette: tilted paddle and handle, generated as filled paths.
# One continuous filled silhouette: head northeast, short handle southwest.
# Coordinates bake the approximately 45-degree direction into the path.
symbol = shape(
    f"M{CX-11} {CY+14} Q{CX-14} {CY+16} {CX-16} {CY+12} "
    f"L{CX-6} {CY+2} "
    f"C{CX-12} {CY-5} {CX-4} {CY-16} {CX+4} {CY-15} "
    f"C{CX+13} {CY-15} {CX+17} {CY-7} {CX+12} {CY} "
    f"C{CX+8} {CY+6} {CX+3} {CY+8} {CX-1} {CY+5}Z"
)
symbol = transformed(symbol, Transform().translate(CX, CY).scale(.95).translate(-CX, -CY))
fallback = svgpath(outlined(symbol), INK) + svgpath(symbol, "#fff6f3")
shield = svgpath(ellipse(CX, CY, R, R), INK) + svgpath(
    ellipse(CX, CY, R - 5.5, R - 5.5), "var(--emblem, #d742c5)"
)
body = (
    '<g class="sthings-bling" data-bling="initial">'
    + shield
    + '<g data-initial="fallback">'
    + fallback
    + "</g></g>"
)
(ROOT / "web/static/img/pip/bling-initial.svg").write_text(
    '<svg viewBox="0 0 420 420" xmlns="http://www.w3.org/2000/svg">\n'
    + body
    + "</svg>\n"
)
