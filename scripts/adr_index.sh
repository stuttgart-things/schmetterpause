#!/bin/sh
# Prints the ADR index for docs/adr/index.md.
#
# Generated rather than kept by hand, and not by an MkDocs plugin either: the
# shared Pages workflow drops every plugin but search before it builds, so an
# index that exists only as a plugin would render on a laptop and be missing
# from the published site. A file in the repository is the one form that
# survives that.
#
# Reads the two lines every ADR already starts with — the "# ADR-NNNN: title"
# heading and the "- **Status:**" bullet — so an ADR that is written the way
# the others are needs nothing added to it. One that is not fails loudly here
# instead of appearing in the table with an empty column.
#
# Write it with "task docs:index"; scripts/docs_test.sh fails the build when
# what is committed no longer matches.
set -eu

cd "$(dirname "$0")/.."

cat <<'HEADER'
<!-- Generated by scripts/adr_index.sh — do not edit. Run "task docs:index". -->

# Entscheidungen

Jede Entscheidung, die das Datenmodell, die Anmeldung oder das Deployment
festlegt, steht hier mit den Alternativen, die dabei verworfen wurden. Eine
Änderung, die einem ADR widerspricht, braucht ein neues ADR mit
`supersedes`-Verweis — kein stiller Umbau.

| Nr. | Entscheidung | Status | Datum |
| --- | --- | --- | --- |
HEADER

for adr in docs/adr/[0-9]*.md; do
	file=${adr##*/}
	number=${file%%-*}

	title=$(sed -n '1s/^# ADR-[0-9][0-9]*: *//p' "$adr")
	status=$(sed -n 's/^- \*\*Status:\*\* *//p' "$adr" | head -1)
	date=$(sed -n 's/^- \*\*Datum:\*\* *//p' "$adr" | head -1)

	for field in title status date; do
		eval "value=\$$field"
		if [ -z "$value" ]; then
			echo "$adr: no $field — the heading must read" \
				"'# ADR-NNNN: Titel' and the header must carry" \
				"'- **Status:**' and '- **Datum:**'" >&2
			exit 1
		fi
	done

	printf '| %s | [%s](%s) | %s | %s |\n' \
		"$number" "$title" "$file" "$status" "$date"
done
